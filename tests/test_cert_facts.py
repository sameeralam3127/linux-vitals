"""Tests for the linux_vitals_cert_facts module and the vitals_certs findings.

The module is exercised against real certificates generated by `openssl` into
a temporary directory, rather than against recorded fixtures, because the
thing most likely to break is the parsing of `openssl`'s own output -- and a
fixture would freeze whatever that looked like on the machine the fixture was
captured on.

Tests that need `openssl` skip when it is absent rather than fail; the module
already degrades to "no certificates" on such a host, which is asserted
separately.

See issue #15.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

from test_templates import REPO_ROOT, _ansible_playbook_bin, _base_env

CERTS_TASKS = REPO_ROOT / "roles" / "vitals_certs" / "tasks" / "main.yml"
CERTS_DEFAULTS = REPO_ROOT / "roles" / "vitals_certs" / "defaults" / "main.yml"

openssl_required = pytest.mark.skipif(
    shutil.which("openssl") is None,
    reason="openssl is not installed on this machine",
)


def _make_cert(directory: Path, name: str, days: int, *, digest: str = "sha256",
               common_name: str = "example.test") -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    subprocess.run(
        [
            "openssl", "req", "-x509",
            f"-{digest}",
            "-newkey", "rsa:2048",
            "-keyout", str(directory / f"{name}.key"),
            "-out", str(path),
            "-days", str(days),
            "-nodes",
            "-subj", f"/CN={common_name}",
        ],
        check=True,
        capture_output=True,
    )
    return path


def _run_module(tmp_path: Path, **params) -> dict:
    task = {
        "name": "Collect certificate facts",
        "sameeralam3127.linux_vitals.linux_vitals_cert_facts": params,
        "register": "facts",
    }
    dump = {
        "name": "Write results for assertion",
        "ansible.builtin.copy": {
            "content": "{{ facts | to_nice_json }}\n",
            "dest": "{{ output_dir }}/cert_facts.json",
            "mode": "0644",
        },
    }
    playbook = [
        {
            "name": "Exercise linux_vitals_cert_facts",
            "hosts": "localhost",
            "connection": "local",
            "gather_facts": False,
            "vars": {
                "output_dir": "{{ lookup('ansible.builtin.env', 'TEST_OUTPUT_DIR') }}"
            },
            "tasks": [task, dump],
        }
    ]
    path = tmp_path / "cert_facts_case.yml"
    path.write_text(yaml.safe_dump(playbook, sort_keys=False), encoding="utf-8")
    subprocess.run(
        [_ansible_playbook_bin(), str(path)],
        check=True,
        cwd=REPO_ROOT,
        env=_base_env(tmp_path),
    )
    return json.loads((tmp_path / "cert_facts.json").read_text(encoding="utf-8"))


