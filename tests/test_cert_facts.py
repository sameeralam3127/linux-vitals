def test_an_unreachable_endpoint_is_reported_as_data_not_a_failure(
    tmp_path: Path,
) -> None:
    # Port 1 on localhost: refused immediately, so this needs no network and
    # cannot hang CI.
    result = _run_module(
        tmp_path,
        paths=[],
        endpoints=[{"host": "127.0.0.1", "port": 1}],
        timeout=2,
    )

    assert len(result["endpoints"]) == 1
    endpoint = result["endpoints"][0]
    assert endpoint["host"] == "127.0.0.1"
    assert "error" in endpoint
    assert endpoint["not_after"] is None


def test_an_endpoint_without_a_host_is_reported_not_crashed(
    tmp_path: Path,
) -> None:
    result = _run_module(tmp_path, paths=[], endpoints=[{"port": 443}])

    assert result["endpoints"][0]["error"] == "endpoint has no host"


