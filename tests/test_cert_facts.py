@openssl_required
def test_a_certificate_on_disk_is_parsed_with_its_expiry(tmp_path: Path) -> None:
    certs = tmp_path / "certs"
    _make_cert(certs, "web.crt", days=400, common_name="web.example.test")

    result = _run_module(tmp_path, paths=[str(certs)])

    assert result["openssl_available"] is True
    found = [c for c in result["certificates"] if c["path"].endswith("web.crt")]
    assert len(found) == 1
    cert = found[0]
    assert "web.example.test" in cert["subject"]
    assert cert["expired"] is False
    # openssl dates are whole days and the comparison is against "now", so the
    # count lands on 399 or 400 depending on the second the test runs.
    assert 395 <= cert["days_remaining"] <= 400
    assert cert["self_signed"] is True
    assert cert["fingerprint_sha256"].count(":") == 31


@openssl_required
def test_an_expired_certificate_is_reported_as_expired(tmp_path: Path) -> None:
    # Issued with a validity window entirely in the past, which is the only
    # way to get openssl to produce an already-expired certificate.
    certs = tmp_path / "certs"
    certs.mkdir(parents=True, exist_ok=True)
    path = certs / "expired.crt"
    subprocess.run(
        [
            "openssl", "req", "-x509", "-newkey", "rsa:2048",
            "-keyout", str(certs / "expired.key"),
            "-out", str(path),
            "-not_before", "20200101000000Z",
            "-not_after", "20200201000000Z",
            "-nodes", "-subj", "/CN=expired.example.test",
        ],
        check=True,
        capture_output=True,
    )

    result = _run_module(tmp_path, paths=[str(certs)])

    cert = next(c for c in result["certificates"] if c["path"].endswith("expired.crt"))
    assert cert["expired"] is True
    assert cert["days_remaining"] < 0, "an expired certificate must count down past zero"


@openssl_required
def test_a_private_key_matching_the_patterns_is_skipped_not_reported(
    tmp_path: Path,
) -> None:
    # The default patterns match *.pem, and a letsencrypt live/ directory is
    # mostly privkey.pem. Reporting those as broken certificates would
    # manufacture a finding per host per renewal directory.
    certs = tmp_path / "certs"
    _make_cert(certs, "real.pem", days=100)
    (certs / "privkey.pem").write_text(
        "-----BEGIN PRIVATE KEY-----\nnotacert\n-----END PRIVATE KEY-----\n",
        encoding="utf-8",
    )

    result = _run_module(tmp_path, paths=[str(certs)], file_patterns=["*.pem"])

    paths = [c["path"] for c in result["certificates"]]
    assert any(p.endswith("real.pem") for p in paths)
    assert not any(p.endswith("privkey.pem") for p in paths)


@openssl_required
def test_a_weak_signature_algorithm_is_reported(tmp_path: Path) -> None:
    certs = tmp_path / "certs"
    _make_cert(certs, "weak.crt", days=200, digest="sha1")

    result = _run_module(tmp_path, paths=[str(certs)])

    cert = next(c for c in result["certificates"] if c["path"].endswith("weak.crt"))
    assert "sha1" in cert["signature_algorithm"].lower()


def test_a_missing_path_is_skipped_rather_than_failing_the_run(
    tmp_path: Path,
) -> None:
    # A cert directory that does not exist on a given host is the normal case
    # in a mixed fleet, not an error.
    result = _run_module(tmp_path, paths=["/nonexistent/certificates"])

    assert result["certificates"] == []
    assert result["scanned_paths"] == []
    # The module returned data rather than failing the task, which is the point.
    assert result["failed"] is False


@openssl_required
def test_max_depth_bounds_the_search(tmp_path: Path) -> None:
    certs = tmp_path / "certs"
    _make_cert(certs / "a" / "b" / "c", "deep.crt", days=100)
    _make_cert(certs, "shallow.crt", days=100)

    shallow = _run_module(tmp_path, paths=[str(certs)], max_depth=1)
    deep = _run_module(tmp_path, paths=[str(certs)], max_depth=5)

    shallow_paths = [c["path"] for c in shallow["certificates"]]
    deep_paths = [c["path"] for c in deep["certificates"]]
    assert any(p.endswith("shallow.crt") for p in shallow_paths)
    assert not any(p.endswith("deep.crt") for p in shallow_paths)
    assert any(p.endswith("deep.crt") for p in deep_paths)


