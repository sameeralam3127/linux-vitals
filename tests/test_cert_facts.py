def test_the_role_is_opt_in() -> None:
    defaults = yaml.safe_load(CERTS_DEFAULTS.read_text(encoding="utf-8"))

    assert defaults["linux_vitals_certs_enabled"] is False
    # Enabling the role must not start scanning the network.
    assert defaults["linux_vitals_cert_endpoints"] == []


def test_the_critical_window_is_inside_the_warning_window() -> None:
    defaults = yaml.safe_load(CERTS_DEFAULTS.read_text(encoding="utf-8"))

    assert (
        defaults["linux_vitals_cert_critical_days"]
        < defaults["linux_vitals_cert_warning_days"]
    ), "a critical window wider than the warning window can never fire"


def test_every_task_is_gated_on_the_opt_in_switch() -> None:
    document = yaml.safe_load(CERTS_TASKS.read_text(encoding="utf-8"))

    assert len(document) == 1, "tasks/main.yml should be one gated block"
    top = document[0]
    assert top["when"] == "linux_vitals_certs_enabled | bool"
    assert "certs" in top["tags"]
    assert "block" in top


def test_the_trust_store_is_excluded_from_expiry_reporting_by_default() -> None:
    # The system CA bundle is hundreds of root certificates that are not
    # yours, several of which are always near expiry. Reporting on them would
    # bury every real finding.
    defaults = yaml.safe_load(CERTS_DEFAULTS.read_text(encoding="utf-8"))

    trust = defaults["linux_vitals_cert_trust_store_paths"]
    assert "/etc/ssl/certs" in trust
    # ...but it is still scanned, so an expired cert in the bundle is visible.
    assert "/etc/ssl/certs" in defaults["linux_vitals_cert_fs_paths"]
